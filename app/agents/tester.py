"""Agent that evaluates generated code through an isolated test-runner tool."""

import json
from collections.abc import Sequence
from pathlib import PurePosixPath, PureWindowsPath

from pydantic import BaseModel, ConfigDict, ValidationError

from app.agents.base_agent import (
    AgentInput,
    AgentOutput,
    BaseAgent,
    LLMClient,
)
from app.llm import create_groq_chat_model
from app.models.schemas import GeneratedFile, TestResult
from app.tools.test_runner import (
    DockerTestRunner,
    TestExecutionResult,
    TestExecutionStatus,
    TestRunner,
)

_TEST_GENERATION_PROMPT = """\
You are DevForge AI's testing agent. Write focused, deterministic pytest tests
for the supplied generated source files. Return only a JSON object with a
"files" array; each item must contain file_path, content, and
programming_language. Put tests under tests/ with filenames beginning
"test_". Test the stated behavior and edge cases that follow from the code;
do not add requirements or change the source files. Tests will execute in an
isolated container and are not assumed to be safe or correct until reviewed.
"""

_SUPPORTED_LANGUAGES = frozenset({"python", "python3"})


class GeneratedTestsResponse(BaseModel):
    """Validated envelope for test files generated by the testing agent."""

    model_config = ConfigDict(extra="forbid")

    files: list[GeneratedFile]


class TesterAgent(BaseAgent):
    """Run project tests and return results plus debugging-oriented feedback."""

    def __init__(
        self,
        llm: LLMClient | None = None,
        test_runner: TestRunner | None = None,
    ) -> None:
        super().__init__(
            agent_name="Tester",
            role="Evaluate generated source code with isolated tests",
            llm=llm if llm is not None else create_groq_chat_model(),
            system_prompt=_TEST_GENERATION_PROMPT,
        )
        self._test_runner = (
            test_runner if test_runner is not None else DockerTestRunner()
        )

    def execute(self, request: AgentInput) -> AgentOutput:
        """Implement BaseAgent's interface for testing generated project files."""
        raw_files = request.context.get("generated_files")
        language = request.context.get("programming_language")
        if not isinstance(raw_files, list):
            raise TypeError(
                "'generated_files' must be a list of generated file objects."
            )
        if not isinstance(language, str) or not language.strip():
            raise TypeError("'programming_language' must be a non-empty string.")

        try:
            files = [GeneratedFile.model_validate(file_data) for file_data in raw_files]
        except ValidationError as error:
            raise ValueError("Input contains invalid generated file data.") from error

        result = self.test_generated_files(files, language.strip())
        return AgentOutput(
            agent_name=self.agent_name,
            content=json.dumps(result.model_dump(mode="json"), indent=2),
        )

    def test_generated_files(
        self,
        generated_files: Sequence[GeneratedFile],
        programming_language: str,
    ) -> TestResult:
        """Generate tests when absent, then delegate all execution to the runner."""
        language = programming_language.strip()
        if language.casefold() not in _SUPPORTED_LANGUAGES:
            return self._result_from_execution(
                TestExecutionResult(
                    status=TestExecutionStatus.UNSUPPORTED_LANGUAGE,
                    execution_error=(
                        f"No isolated testing framework is configured for "
                        f"'{language}'. Currently supported: Python with pytest."
                    ),
                )
            )
        if not generated_files:
            return TestResult(
                execution_error="No generated source files were provided for testing.",
                actionable_feedback=[
                    "Provide source files for the assigned development task."
                ],
            )

        source_files = list(generated_files)
        if not any(self._is_test_file(file.file_path) for file in source_files):
            try:
                generated_tests = self._generate_tests(source_files, language)
            except (ValueError, RuntimeError) as error:
                return TestResult(
                    execution_error=f"Could not prepare tests: {error}",
                    actionable_feedback=[
                        "Add pytest files under tests/ or correct the test-generation response."
                    ],
                )
            source_files.extend(generated_tests)

        execution = self._test_runner.run(source_files, language)
        return self._result_from_execution(execution)

    def _generate_tests(
        self,
        source_files: Sequence[GeneratedFile],
        programming_language: str,
    ) -> list[GeneratedFile]:
        """Generate test files only; validate that they cannot replace source."""
        request = AgentInput(
            task="Create focused pytest coverage for the supplied project files.",
            context={
                "programming_language": programming_language,
                "project_structure": [file.file_path for file in source_files],
                "generated_source_files": [
                    file.model_dump(mode="json") for file in source_files
                ],
            },
        )
        response = self.run_llm(request)
        try:
            payload = json.loads(response.content)
            generated = GeneratedTestsResponse.model_validate(payload)
        except (json.JSONDecodeError, ValidationError) as error:
            raise ValueError(
                "The LLM returned malformed structured test files."
            ) from error

        if not generated.files:
            raise ValueError(
                "The LLM returned no tests and the project has no test files."
            )

        existing_paths = {file.file_path.casefold() for file in source_files}
        seen_paths: set[str] = set()
        for test_file in generated.files:
            path = test_file.file_path
            posix_path = PurePosixPath(path)
            windows_path = PureWindowsPath(path)
            if (
                "\\" in path
                or "\x00" in path
                or ":" in path
                or posix_path.is_absolute()
                or windows_path.is_absolute()
                or windows_path.drive
                or any(part in {"", ".", ".."} for part in path.split("/"))
                or not path.casefold().startswith("tests/")
                or not self._is_test_file(path)
            ):
                raise ValueError(
                    f"Generated test path '{path}' must be a relative tests/test_*.py path."
                )
            path_key = posix_path.as_posix().casefold()
            if path_key in existing_paths or path_key in seen_paths:
                raise ValueError(
                    f"Generated test path '{path}' conflicts with another file."
                )
            if (
                test_file.programming_language.casefold()
                != programming_language.casefold()
            ):
                raise ValueError(
                    f"Generated test '{path}' uses a different programming language."
                )
            if not test_file.content.strip():
                raise ValueError(f"Generated test '{path}' is empty.")
            seen_paths.add(path_key)
        return generated.files

    @staticmethod
    def _is_test_file(file_path: str) -> bool:
        """Check for pytest's standard test filename within any project directory."""
        name = PurePosixPath(file_path).name
        return name.startswith("test_") and name.endswith(".py")

    def _result_from_execution(self, execution: TestExecutionResult) -> TestResult:
        """Map runner status into test counts, execution errors, and next steps."""
        output = execution.output.strip()
        error_details = (
            [output]
            if execution.status is TestExecutionStatus.FAILED and output
            else []
        )
        execution_error = execution.execution_error
        feedback: list[str] = []

        if execution.status is TestExecutionStatus.FAILED:
            feedback.append(
                "Review the failing test names and assertions, then fix the generated "
                "implementation or tests in a follow-up development task."
            )
        elif execution.status is TestExecutionStatus.ERROR:
            feedback.append(
                "Resolve the test collection, syntax, import, or runner error before "
                "treating the test results as meaningful."
            )
        elif execution.status is TestExecutionStatus.TIMEOUT:
            feedback.append(
                "Inspect the slow or blocked test and reduce its work; rerun only after "
                "reviewing its resource use."
            )
        elif execution.status is TestExecutionStatus.MISSING_TESTS:
            feedback.append("Add pytest tests under tests/ or files named test_*.py.")
        elif execution.status is TestExecutionStatus.SANDBOX_UNAVAILABLE:
            feedback.append(
                "Start Docker Desktop and build the isolated test runner image."
            )
        elif execution.status is TestExecutionStatus.UNSUPPORTED_LANGUAGE:
            feedback.append(
                "Configure an isolated runner image and adapter for the requested language."
            )

        if output and execution.status not in {
            TestExecutionStatus.PASSED,
            TestExecutionStatus.FAILED,
        }:
            error_details.append(output)
        return TestResult(
            total_tests=execution.total_tests,
            passed_tests=execution.passed_tests,
            failed_tests=execution.failed_tests,
            execution_status=execution.status.value,
            exit_code=execution.exit_code,
            stdout=execution.stdout,
            stderr=execution.stderr,
            output=execution.output,
            execution_duration=execution.execution_duration,
            execution_environment=(
                "Docker"
                if isinstance(self._test_runner, DockerTestRunner)
                else type(self._test_runner).__name__
            ),
            error_details=error_details,
            execution_error=execution_error,
            actionable_feedback=feedback,
        )
